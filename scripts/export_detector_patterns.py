#!/usr/bin/env python3
"""Export detector patterns: Python registry -> key-sentry JSON.

The Python detector registry (detectors/registry.py) is canonical. The
web app must NOT duplicate detector regexes by hand — it reads
key-sentry/lib/detector-patterns.json, generated by this script.

Usage:
  python3 scripts/export_detector_patterns.py [--output PATH]

Default output: ../../key-sentry/lib/detector-patterns.json (relative
to this script: <workspace>/key-sentry/lib/detector-patterns.json).

A pytest test (tests/test_vibe.py) regenerates the export in a temp
dir and asserts it matches the live registry, so drift is caught.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from detectors.registry import DETECTORS  # noqa: E402

DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))),
    "key-sentry", "lib", "detector-patterns.json")


def export_patterns() -> dict:
    """Serialize the live registry: provider, regex, description."""
    detectors = []
    for det in DETECTORS:
        detectors.append({
            "provider": det.provider,
            "cred_type": det.cred_type,
            "pattern": det.pattern,  # None = entropy/context only
            "console_url": det.console_url,
            "severity": det.severity,
            "requires_context": det.requires_context,
        })
    return {
        "generated_from": "ai-key-scanner/detectors/registry.py",
        "note": "Generated — do not edit by hand. Regenerate with "
                "scripts/export_detector_patterns.py. The Python "
                "registry is canonical.",
        "detectors": detectors,
    }


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Export detector patterns to the web app JSON.")
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    data = export_patterns()
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    print(f"wrote {len(data['detectors'])} detector patterns to "
          f"{args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
