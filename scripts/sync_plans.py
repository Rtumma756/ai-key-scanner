#!/usr/bin/env python3
"""Sync plan definitions: canonical JSON -> key-sentry JSON.

The canonical plan definitions live in
docs/commercial/plans.json. The web app must NOT duplicate them by
hand — it reads key-sentry/lib/plans.json, generated by this script
(verbatim copy, so the two files stay identical).

Usage:
  python3 scripts/sync_plans.py [--output PATH]

Default output: ../../key-sentry/lib/plans.json (relative to this
script: <workspace>/key-sentry/lib/plans.json).

A pytest test (tests/test_plans.py) regenerates the sync in a temp
dir and asserts it matches the canonical file, so drift is caught.
Same pattern as scripts/export_detector_patterns.py.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil

CANONICAL = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "docs", "commercial", "plans.json")

DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__)))),
    "key-sentry", "lib", "plans.json")


def sync_plans(canonical: str = CANONICAL, output: str = DEFAULT_OUTPUT) -> dict:
    """Copy the canonical plans.json to the web app (verbatim).

    Returns the parsed plan data (also validates it is JSON first, so
    a broken canonical file never overwrites a good generated copy).
    """
    with open(canonical, encoding="utf-8") as fh:
        data = json.load(fh)
    os.makedirs(os.path.dirname(output), exist_ok=True)
    shutil.copyfile(canonical, output)
    return data


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Sync canonical plan definitions to the web app JSON.")
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    parser.add_argument("--canonical", default=CANONICAL)
    args = parser.parse_args(argv)
    data = sync_plans(args.canonical, args.output)
    print(f"synced {len(data.get('tiers', {}))} plan tiers to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
